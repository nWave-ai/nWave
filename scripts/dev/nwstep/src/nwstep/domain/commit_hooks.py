"""The commit hooks a working clone must carry, and the decisions over their state.

Values only: no file, git, process or clock is read here. The effects that observe the clone live in the
infrastructure module that calls these functions.
"""

from __future__ import annotations

from enum import Enum


HOOK_TYPES: tuple[str, ...] = ("pre-commit", "commit-msg")
GENERATED_MARKER = b"File generated by pre-commit"


class HookFile(Enum):
    ABSENT = "absent"
    GENERATED = "generated"
    FOREIGN = "foreign"


class HookPlan(Enum):
    ALREADY_INSTALLED = "already-installed"
    INSTALL = "install"
    HOOKS_PATH_SET = "hooks-path-set"
    INSTALLER_MISSING = "installer-missing"
    NOT_DECLARED = "not-declared"


class HookOutcome(Enum):
    NOT_A_WORK_TREE = "not-a-work-tree"
    NOT_DECLARED = "not-declared"
    GIT_UNAVAILABLE = "git-unavailable"
    ALREADY_INSTALLED = "already-installed"
    INSTALLED = "installed"
    INSTALLED_KEEPING_FOREIGN = "installed-keeping-foreign"


def classify(content: bytes | None) -> HookFile:
    if content is None:
        return HookFile.ABSENT
    if GENERATED_MARKER in content:
        return HookFile.GENERATED
    return HookFile.FOREIGN


def is_installed(files: tuple[HookFile, ...]) -> bool:
    return all(file is HookFile.GENERATED for file in files)


def plan_hooks(
    files: tuple[HookFile, ...],
    *,
    declared: bool,
    hooks_path_set: bool,
    installer_available: bool,
) -> HookPlan:
    if not declared:
        return HookPlan.NOT_DECLARED
    if hooks_path_set:
        return HookPlan.HOOKS_PATH_SET
    if is_installed(files):
        return HookPlan.ALREADY_INSTALLED
    if not installer_available:
        return HookPlan.INSTALLER_MISSING
    return HookPlan.INSTALL


def installed_outcome(before: tuple[HookFile, ...]) -> HookOutcome:
    if HookFile.FOREIGN in before:
        return HookOutcome.INSTALLED_KEEPING_FOREIGN
    return HookOutcome.INSTALLED
