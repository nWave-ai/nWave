#: Files each adapter may read before planning; writers discover the rest.
ADAPTER_PATHS = {
    "omp": (".omp/agent/config.yml",),
    "claude-code": (),
    "codex": (".codex/config.toml", ".codex/agents"),
    "copilot": (),
    "opencode": (".config/opencode/opencode.json",),
    "devin": (),
}

#: Directories an adapter may scan for its files (copilot discovers role files).
ADAPTER_SCANS = {
    "copilot": (".copilot/agents", "*.md"),
    "claude-code": (".claude/agents/nw", "*.md"),
}


def adapter_paths(name: str) -> tuple[str, ...]:
    return ADAPTER_PATHS.get(name, ())


def adapter_scan(name: str) -> tuple[str, str] | None:
    """(home-relative directory, glob) to read before planning, or None."""
    return ADAPTER_SCANS.get(name)


def adapter_for(name: str) -> HostAdapter | None:
    return next((adapter for adapter in HOST_ADAPTERS if adapter.name == name), None)


def plan_host_writes(
    hosts: tuple[str, ...], facts: tuple[ModelFact, ...], existing: dict[str, bytes]
) -> tuple[HostResolution, ...]:
    """The pure per-host plan: disclosures, refusals and file patches."""
    plans: list[HostResolution] = []
    for name in hosts:
        adapter = adapter_for(name)
        if adapter is None or adapter.apply is None:
            continue
        prefix = adapter_prefixes(adapter)
        scoped = {
            path: raw for path, raw in existing.items() if path.startswith(prefix)
        }
        plans.append(adapter.apply(scoped, facts))
    return tuple(plans)


def adapter_prefixes(adapter: HostAdapter) -> str:
    return {
        "omp": ".omp/agent/",
        "claude-code": ".claude/",
        "codex": ".codex/",
        "copilot": ".copilot/",
        "opencode": ".config/opencode/",
        "devin": ".config/devin/",
    }.get(adapter.name, "")
