"""The host adapter registry of the ``nwave-ai rigor`` command.

One adapter per host, each a frozen record of pure functions and data: adding a
host later means adding one record and nothing else (INV4's extension rule).
Every apply function maps a model fact to a pure write plan over the existing
file bytes; it never touches the file system itself.

Guarantees encoded here (design record):
- INV4  host files are written only for hosts the person confirmed.
- INV7  an unverified-host write carries its source (url and date) as data and
        is disclosed before confirmation.
- INV8  the previous bytes are kept in a ``.nwave-bak`` copy that is never
        overwritten.
- INV9  a host with no documented per-role surface refuses, naming what it
        looked for and the source it checked.
- INV10 an existing host file whose structure does not match the documented
        shape is never written; the refusal shows its first lines and names the
        difference.
- INV11 every write line for an unverified host reads ``format not verified:
        format X assumed from source Y``.

Format sources (owner rule: verified from the host's own installation or its
published documentation; dates recorded):
- omp        verified on this machine, 2026-11-09: ``~/.omp/agent/config.yml``
             key ``task.agentModelOverrides`` maps role names to
             ``provider/model`` strings (an ``:variant`` suffix may follow).
- opencode   documented, https://opencode.ai/docs/agents/ (2026-11-09):
             ``agents.<name>.model`` = ``provider/model`` in
             ``~/.config/opencode/opencode.json(c)``. The documentation states
             this is the version 2 configuration format; a version 1 install
             may ignore the key, and the summary says so. Not verified locally.
- copilot    documented, https://docs.github.com/en/copilot/how-tos/copilot-cli/customize-copilot/create-custom-agents-for-cli
             (2026-11-09): a custom agent file
             ``~/.copilot/agents/<id>.agent.md`` carries frontmatter; the
             ``model`` field appears only in the example for a locally added
             provider-qualified model. Cloud model names are not documented.
             Not verified locally.
- claude-code documented and verified on this machine,
             https://code.claude.com/docs/en/sub-agents (2026-11-09): a
             subagent file ``~/.claude/agents/nw/<role>.md`` carries YAML
             frontmatter with a per-subagent ``model`` field (an alias, a
             full model id such as claude-opus-5-5, or inherit); the
             directory is scanned recursively and identity comes from the
             ``name`` field. The files are regenerated by an nWave reinstall.
- codex      refused. Verified on this machine, 2026-11-09: the agent files
             ``~/.codex/agents/nw-<role>.toml`` are nWave-authored and carry
             no model key (their first line says the declared model is not
             projected: host mapping pending); the documented configuration,
             https://learn.chatgpt.com/docs/config-file/config-reference
             (2026-11-09), has one top-level ``config.toml`` ``model`` only,
             so the adapter refuses naming the file and what was looked for.
- devin      documented, https://docs.devin.ai/cli/models.md (2026-11-09): the
             config file documents one default ``agent.model`` and pinned
             models; no per-role surface, so the adapter refuses.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import TYPE_CHECKING


if TYPE_CHECKING:
    from collections.abc import Callable

import yaml  # type: ignore[import-untyped]

from nwave_ai.platform.rigor_core import ModelFact, Refusal


UNVERIFIED_LINE = "format not verified on this machine (source: {source})"


@dataclass(frozen=True)
class HostResolution:
    """One host's outcome in the pure write plan."""

    name: str
    refusal: Refusal | None = None
    disclosure: str = ""  # printed before confirmation
    files: tuple[tuple[str, bytes], ...] = ()  # home-relative path -> new bytes
    backup: tuple[str, ...] = ()  # previous bytes move to path + ".nwave-bak"


@dataclass(frozen=True)
class FormatSource:
    """Where a host's format knowledge comes from (INV7 data, not prose)."""

    url: str
    date: str
    verified: bool
    caveat: str = ""


@dataclass(frozen=True)
class HostAdapter:
    name: str
    source: FormatSource
    per_role: bool
    refuse_what: str = ""  # non-empty: the host always refuses
    apply: Callable[[dict[str, bytes], tuple[ModelFact, ...]], HostResolution] | None = None


def _unreadable(name: str, path: str, raw: bytes | None, error: str) -> HostResolution:
    """Shared refusal: an existing file whose bytes we cannot parse is never written."""
    return HostResolution(
        name=name,
        refusal=Refusal(
            f"The {name} configuration is not readable, so it was not written.",
            f"{path}: {error}",
            "Fix or restore the file; its first lines: "
            + _first_lines(raw if raw is not None else b""),
        ),
    )


def _structure_mismatch(
    name: str, path: str, raw: bytes | None, expected: str
) -> HostResolution:
    """Shared refusal: a file that parses but has another shape is never written."""
    return HostResolution(
        name=name,
        refusal=Refusal(
            f"The {name} file does not match the documented shape, so it was not "
            "written.",
            f"{path} differs from the expected structure: {expected}",
            "Compare its first lines with the documented shape: "
            + _first_lines(raw if raw is not None else b""),
        ),
    )


def _first_lines(raw: bytes, count: int = 3) -> str:
    try:
        text = raw.decode("utf-8")
    except UnicodeError:
        return "<unreadable bytes>"
    lines = text.splitlines()
    return "\n".join(lines[:count]) if lines else "<empty file>"


def _write_line(adapter: HostAdapter) -> str:
    if adapter.source.verified:
        return (
            f"format verified on this machine (source: {adapter.source.url}, "
            f"{adapter.source.date})"
        )
    return (
        f"format not verified: format {adapter.name} assumed from source "
        f"{adapter.source.url}"
    )


def _omp_apply(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    """Update ``task.agentModelOverrides`` in the omp agent configuration."""
    path = ".omp/agent/config.yml"
    raw = existing.get(path)
    overrides: dict[str, str] = {}
    document: dict[str, object] = {}
    if raw is not None:
        try:
            document = yaml.safe_load(raw.decode("utf-8"))
        except (yaml.YAMLError, UnicodeError) as error:
            return HostResolution(
                name="omp",
                refusal=Refusal(
                    "The omp configuration is not readable YAML, so it was not "
                    "written.",
                    f"{path}: {error}",
                    "Fix or restore the file; its first lines: "
                    + _first_lines(raw if raw is not None else b""),
                ),
            )
        if document is None:
            document = {}
        if not isinstance(document, dict):
            return _structure_mismatch(
                "omp",
                path,
                raw,
                "the file parses to a mapping that carries "
                "task.agentModelOverrides",
            )
        task_any = document.get("task")
        task = dict(task_any) if isinstance(task_any, dict) else None
        if task is not None and not isinstance(task, dict):
            return _structure_mismatch(
                "omp",
                path,
                raw,
                "task is a mapping that carries agentModelOverrides",
            )
        current = (task or {}).get("agentModelOverrides")
        if current is not None:
            if not isinstance(current, dict):
                return _structure_mismatch(
                    "omp",
                    path,
                    raw,
                    "task.agentModelOverrides is a mapping of role to model",
                )
            overrides = dict(current)
    for fact in facts:
        overrides[fact.target] = f"{fact.provider}/{fact.model}"
    task_section = dict(task or {})
    task_section["agentModelOverrides"] = overrides
    document["task"] = task_section
    written = yaml.safe_dump(
        document, default_flow_style=False, sort_keys=True, allow_unicode=True
    ).encode("utf-8")
    return HostResolution(
        name="omp",
        files=((path, written),),
        backup=(path,) if raw is not None else (),
        disclosure=(
            "omp: " + path + " — " + write_line(_OMP_ADAPTER)
            + " Comments in this yaml file will be lost; the previous bytes "
            "stay in " + path + ".nwave-bak."
        ),
    )


def _opencode_apply(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    """Update ``agents.<role>.model`` in the opencode JSON configuration."""
    path = ".config/opencode/opencode.json"
    raw = existing.get(path)
    document: dict[str, object] = {}
    if raw is not None:
        try:
            document = json.loads(raw.decode("utf-8"))
        except (ValueError, UnicodeError) as error:
            return HostResolution(
                name="opencode",
                refusal=Refusal(
                    "The opencode configuration is not readable JSON, so it was "
                    "not written.",
                    f"{path}: {error}",
                    "Fix or restore the file; its first lines: "
                    + _first_lines(raw if raw is not None else b""),
                ),
            )
        if not isinstance(document, dict):
            return HostResolution(
                name="opencode",
                refusal=Refusal(
                    "The opencode configuration is not a JSON object, so it was "
                    "not written.",
                    f"{path} holds {type(document).__name__}; the writer expects "
                    "the documented version 2 object with an agents mapping.",
                    "Compare its first lines with the documented shape: "
                    + _first_lines(raw),
                ),
            )
    agents = document.get("agents")
    if agents is not None and not isinstance(agents, dict):
        return _structure_mismatch(
            "opencode",
            path,
            raw,
            "agents is a mapping of role to its documented options",
        )
    agents = dict(agents or {})
    for fact in facts:
        entry = agents.get(fact.target)
        entry = dict(entry) if isinstance(entry, dict) else {}
        entry["model"] = f"{fact.provider}/{fact.model}"
        agents[fact.target] = entry
    document["agents"] = agents
    written = (json.dumps(document, indent=2, sort_keys=True) + "\n").encode("utf-8")
    caveat = " (documented for the version 2 config format)"
    return HostResolution(
        name="opencode",
        files=((path, written),),
        backup=(path,) if raw is not None else (),
        disclosure=(
            f'opencode: {path} — the exact bytes carry "agents" and "model". '
            + write_line(_OPENCODE_ADAPTER) + " " + caveat
        ),
    )


_COPILOT_FRONTMATTER_FIELDS = (
    "name",
    "description",
    "tools",
    "strict-tools-list",
    "include-custom-instructions",
)


def _copilot_apply(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    """Write ``model:`` into each role's custom agent file frontmatter."""
    files: list[tuple[str, bytes]] = []
    backups: list[str] = []
    for fact in facts:
        path = f".copilot/agents/{fact.target}.agent.md"
        raw = existing.get(path)
        if raw is None:
            frontmatter = (
                f"---\nname: {fact.target}\n"
                f"description: nWave {fact.target} role\n"
                f"model: {fact.provider}/{fact.model}\n---\n"
            )
            files.append((path, frontmatter.encode("utf-8")))
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeError:
            return HostResolution(
                name="copilot",
                refusal=Refusal(
                    "The copilot agent file is not readable UTF-8, so it was not "
                    "written.",
                    path,
                    "Fix or restore the file; its first lines: " + _first_lines(raw),
                ),
            )
        if not text.startswith("---"):
            return HostResolution(
                name="copilot",
                refusal=Refusal(
                    "The copilot agent file has no frontmatter, so it was not written.",
                    f"{path} does not start with ---; the documented agent file "
                    "is YAML frontmatter with fields "
                    + ", ".join(_COPILOT_FRONTMATTER_FIELDS)
                    + ".",
                    "Compare its first lines with the documented shape: "
                    + _first_lines(raw),
                ),
            )
        lines = text.splitlines(keepends=True)
        closing = next(
            (index for index, line in enumerate(lines[1:], 1) if line.strip() == "---"),
            None,
        )
        if closing is None:
            return _structure_mismatch(
                "copilot",
                path,
                raw,
                "frontmatter that closes with a second ---",
            )
        replaced = False
        for index in range(1, closing):
            if lines[index].startswith("model:"):
                lines[index] = f"model: {fact.provider}/{fact.model}\n"
                replaced = True
        if not replaced:
            lines.insert(closing, f"model: {fact.provider}/{fact.model}\n")
        files.append((path, "".join(lines).encode("utf-8")))
        backups.append(path)
    return HostResolution(
        name="copilot",
        files=tuple(files),
        backup=tuple(backups),
        disclosure=(
            "copilot: ~/.copilot/agents/<role>.agent.md — the exact bytes "
            "carry a model: frontmatter line. "
            + write_line(_COPILOT_ADAPTER)
            + " (documented only for provider-qualified local models; cloud "
            "model names not documented)"
        ),
    )


def _claude_code_apply(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    """Write ``model:`` into each role's subagent frontmatter under agents/nw."""
    for fact in facts:
        if fact.provider != "claude":
            return HostResolution(
                name="claude-code",
                refusal=Refusal(
                    f"The claude-code subagent {fact.target} was declared a "
                    f"{fact.provider} model, so nothing was written for it.",
                    f"{fact.provider}/{fact.model} for {fact.target}",
                    "claude-code runs Claude models: the documented subagent "
                    "model values are an alias, a full claude model id such "
                    "as claude-opus-5-5, or inherit. Declare that role with a "
                    "claude model or leave it unset for this host.",
                ),
            )
    files: list[tuple[str, bytes]] = []
    backups: list[str] = []
    for fact in facts:
        path = f".claude/agents/nw/{fact.target}.md"
        raw = existing.get(path)
        if raw is None:
            frontmatter = (
                f"---\nname: {fact.target}\n"
                f"description: nWave {fact.target} role\n"
                f"model: claude-{fact.model.removeprefix('claude-')}\n---\n"
            )
            files.append((path, frontmatter.encode("utf-8")))
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeError:
            return HostResolution(
                name="claude-code",
                refusal=Refusal(
                    "The claude-code subagent file is not readable UTF-8, so it "
                    "was not written.",
                    path,
                    "Fix or restore the file; its first lines: " + _first_lines(raw),
                ),
            )
        if not text.startswith("---"):
            return HostResolution(
                name="claude-code",
                refusal=Refusal(
                    "The claude-code subagent file has no frontmatter, so it was "
                    "not written.",
                    f"{path} does not start with ---; the documented subagent "
                    "file is YAML frontmatter whose first line is ---, with "
                    "name and description required.",
                    "Compare its first lines with the documented shape: "
                    + _first_lines(raw),
                ),
            )
        lines = text.splitlines(keepends=True)
        closing = next(
            (index for index, line in enumerate(lines[1:], 1) if line.strip() == "---"),
            None,
        )
        if closing is None:
            return _structure_mismatch(
                "claude-code",
                path,
                raw,
                "frontmatter that closes with a second ---",
            )
        replaced = False
        for index in range(1, closing):
            if lines[index].startswith("model:"):
                lines[index] = f"model: claude-{fact.model.removeprefix('claude-')}\n"
                replaced = True
        if not replaced:
            lines.insert(closing, f"model: claude-{fact.model.removeprefix('claude-')}\n")
        files.append((path, "".join(lines).encode("utf-8")))
        backups.append(path)
    return HostResolution(
        name="claude-code",
        files=tuple(files),
        backup=tuple(backups),
        disclosure=(
            "claude-code: ~/.claude/agents/nw/<role>.md — the exact bytes "
            "carry a model: frontmatter line whose value is the declared "
            "claude model joined as a full model id (claude-<model>); the "
            "documented values are an alias, a full model id such as "
            "claude-opus-5-5, or inherit; "
            + write_line(_CLAUDE_CODE_ADAPTER)
            + " These files are regenerated by an nWave reinstall, which will "
            "reset any model line written here; the previous bytes stay in a "
            ".nwave-bak copy beside each file."
        ),
    )


def _refuse_host(
    adapter: HostAdapter,
    existing: dict[str, bytes],
    facts: tuple[ModelFact, ...],
) -> HostResolution:
    return HostResolution(
        name=adapter.name,
        refusal=Refusal(
            adapter.refuse_what,
            adapter.source.caveat or "No per-role model surface exists to write.",
            "Apply per-role models to hosts that document them.",
        ),
        disclosure=(
            f"{adapter.name}: cannot express a model per role — see the refusal."
        ),
    )


def _refuse_codex(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    return _refuse_host(_CODEX_ADAPTER, existing, facts)


def _refuse_devin(
    existing: dict[str, bytes], facts: tuple[ModelFact, ...]
) -> HostResolution:
    return _refuse_host(_DEVIN_ADAPTER, existing, facts)


