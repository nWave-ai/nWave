"""Project gitignore policy: the root ``.gitignore`` repair and the nested ``.nwave/.gitignore``.

Composes three former DES sources into one platform owner (S5-OQ1): the explicit project
enable/disable repair (ProjectGitignoreService), the pure root-``.gitignore`` transform and the
shared nested-``.nwave/.gitignore`` helper. Hooks never call the repair and never create
``.nwave`` in an inactive project; the explicit ``nwave-ai project`` command owns that.
"""

from __future__ import annotations

from typing import TYPE_CHECKING


if TYPE_CHECKING:
    from pathlib import Path


_BANNER = "# nWave config (keep .nwave/config.json trackable)"

# Whole-dir ``.nwave`` exclude shapes, mapped to whether they carry a leading
# slash. The transform rewrites any of these to ``<prefix>.nwave/*`` plus the
# matching ``!<prefix>.nwave/config.json`` negation.
_WHOLE_DIR_EXCLUDES: dict[str, str] = {
    ".nwave": "",
    ".nwave/": "",
    "/.nwave": "/",
    "/.nwave/": "/",
}

_MARKER = "# Generated by nWave. Do not edit."
_MARKER_REINCLUDE = "!config.json"
# Canonical nested content ignores everything except the canonical declaration.
# Retired filenames remain ignored and are never reintroduced by runtime code.
_CONTENT = f"{_MARKER}\n*\n{_MARKER_REINCLUDE}\n"


class ProjectGitignoreService:
    """Repair nWave ignore rules without deciding project activation."""

    def __init__(self, *, read_only: bool = False) -> None:
        self._read_only = read_only

    def fix_gitignore(self, *, project_root: Path) -> None:
        """Apply the dual-layer gitignore fix idempotently (ADR-AG-004)."""
        if self._read_only:
            return
        self._fix_root_gitignore(project_root)
        self._fix_nested_gitignore(project_root)

    def _fix_root_gitignore(self, project_root: Path) -> None:
        path = project_root / ".gitignore"
        try:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            fixed = fix_root_gitignore(current)
            if fixed != current:
                path.write_text(fixed, encoding="utf-8")
        except OSError:
            return

    def _fix_nested_gitignore(self, project_root: Path) -> None:
        """Repair the nested ignore via the shared canonical helper."""
        ensure_nwave_gitignore(project_root / ".nwave")


def fix_root_gitignore(content: str) -> str:
    """Return the root ``.gitignore`` content with the marker re-included.

    Args:
        content: current root ``.gitignore`` text.

    Returns:
        transformed text (idempotent: re-applying is a no-op).
    """
    if _already_fixed(content):
        return content

    lines = content.splitlines()
    for index, line in enumerate(lines):
        prefix = _WHOLE_DIR_EXCLUDES.get(line.strip())
        if prefix is None:
            continue
        lines[index] = f"{prefix}.nwave/*"
        lines.insert(index + 1, f"!{prefix}.nwave/config.json")
        return _join(lines)

    return _append_reinclude(content)


def _already_fixed(content: str) -> bool:
    """Whether a marker re-include negation is already present."""
    stripped = {line.strip() for line in content.splitlines()}
    return any(
        line in {"!.nwave/config.json", "!/.nwave/config.json"} for line in stripped
    )


def _append_reinclude(content: str) -> str:
    """Append the banner + re-include block to customized content."""
    base = content if content.endswith("\n") or content == "" else content + "\n"
    return f"{base}{_BANNER}\n.nwave/*\n!.nwave/config.json\n"


def _join(lines: list[str]) -> str:
    return "\n".join(lines) + "\n"


def nested_gitignore_content() -> str:
    """The canonical ``.nwave/.gitignore`` body (banner + ``*`` + config re-include).

    ProjectGitignoreService delegates to this so both nested-gitignore writers emit
    identical, idempotent content and cannot disagree (the EXTEND verdict).
    """
    return _CONTENT


def runtime_gitignore_content() -> bytes:
    """Canonical runtime-only ignore bytes; project configuration lives outside."""
    return f"{_MARKER}\n*\n".encode()


def is_nwave_generated_gitignore(content: str) -> bool:
    """True when ``content`` carries the nWave generation marker.

    The one ownership rule for a ``.nwave/.gitignore``: the writer overwrites,
    and the uninstaller removes, exactly the files this accepts.
    """
    return _MARKER in content


def ensure_nwave_gitignore(path: Path) -> None:
    """Ensure a .gitignore exists in the .nwave/ ancestor of ``path``.

    Walks upward from ``path`` until a directory named ``.nwave`` is found,
    then creates ``.nwave/.gitignore`` with the standard nWave content. If no
    ``.nwave`` ancestor is found, the call is a no-op.

    The canonical content keeps ``config.json`` trackable. Rewriting a
    banner-stamped file is idempotent.

    Args:
        path: Any path inside (or equal to) a ``.nwave`` directory.
    """
    nwave_dir = _find_nwave_ancestor(path)
    if nwave_dir is None:
        return

    gitignore = nwave_dir / ".gitignore"
    try:
        if gitignore.exists():
            content = gitignore.read_text(encoding="utf-8")
            if not is_nwave_generated_gitignore(content):
                # User-customized — do not overwrite.
                return
        gitignore.write_text(_CONTENT, encoding="utf-8")
    except OSError:
        # Read-only directory or permission error — fail silent.
        pass


def _find_nwave_ancestor(path: Path) -> Path | None:
    """Return the nearest ``.nwave`` directory at or above ``path``."""
    current = path
    while current != current.parent:
        if current.name == ".nwave":
            return current
        current = current.parent
    return None
