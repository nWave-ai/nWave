"""Unit tests for `scripts/validation/verify_hooks.py`.

`verify-hooks` guarantees the project's git hooks are genuinely installed
and authoritative — the piece `pre-commit install --overwrite` cannot
guarantee because it cannot detect a `core.hooksPath` bypass. The check
fails loudly (non-zero exit + actionable message) when any required hook
type is missing, foreign (not pre-commit-managed), or silently bypassed via
`core.hooksPath`.

Architecture mirrors the validators in `scripts/validation/`: a pure core
(`check_hooks`) that takes injected state, a thin filesystem/git wrapper,
and a CLI shell. These tests exercise the pure core against injected states
without touching the real repo, plus the config-parsing wrapper on a
tmp_path fixture.

Lean test budget: behavior-first, one test per non-overlapping behavior.
"""

from __future__ import annotations

import importlib.util
import subprocess
from pathlib import Path

import pytest


# ---------------------------------------------------------------------------
# Module-under-test loader — keeps tests independent of repo `sys.path`.
# ---------------------------------------------------------------------------


def _load_module():
    repo_root = Path(__file__).resolve().parents[3]
    target = repo_root / "scripts" / "validation" / "verify_hooks.py"
    spec = importlib.util.spec_from_file_location("verify_hooks", target)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def vh():
    return _load_module()


# Realistic shape of a pre-commit-generated hook file (carries the marker).
_MANAGED = (
    "#!/usr/bin/env bash\n"
    "# File generated by pre-commit: https://pre-commit.com\n"
    "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
)
# A foreign / stale script with no pre-commit marker.
_FOREIGN = "#!/usr/bin/env bash\necho 'custom legacy hook'\n"

_DEFAULT_TYPES = ["pre-commit", "pre-push", "commit-msg"]
_HOOKS_DIR = Path("/repo/.git/hooks")


def _reader_all_managed(hook_type: str) -> str | None:
    return _MANAGED


# ---------------------------------------------------------------------------
# Pure-core tests — check_hooks(hook_types, hooks_dir, hooks_path_config, reader)
# ---------------------------------------------------------------------------


def test_all_present_managed_hookspath_unset_no_problems(vh) -> None:
    """All types present + pre-commit-managed + hooksPath unset → no problems."""
    problems = vh.check_hooks(
        _DEFAULT_TYPES,
        _HOOKS_DIR,
        None,
        _reader_all_managed,
    )
    assert problems == []


def test_missing_required_type_flagged_and_names_type(vh) -> None:
    """A required type with no hook file is flagged, naming the type."""

    def reader(hook_type: str) -> str | None:
        return None if hook_type == "commit-msg" else _MANAGED

    problems = vh.check_hooks(_DEFAULT_TYPES, _HOOKS_DIR, None, reader)
    assert len(problems) == 1
    assert problems[0].kind == "missing"
    assert "commit-msg" in problems[0].detail


def test_foreign_hook_without_marker_flagged_and_names_type(vh) -> None:
    """A present-but-foreign hook (no pre-commit marker) is flagged."""

    def reader(hook_type: str) -> str | None:
        return _FOREIGN if hook_type == "pre-push" else _MANAGED

    problems = vh.check_hooks(_DEFAULT_TYPES, _HOOKS_DIR, None, reader)
    assert len(problems) == 1
    assert problems[0].kind == "foreign"
    assert "pre-push" in problems[0].detail


def test_hookspath_set_to_nondefault_flagged(vh) -> None:
    """core.hooksPath pointing elsewhere is flagged — git ignores .git/hooks."""
    problems = vh.check_hooks(
        _DEFAULT_TYPES,
        _HOOKS_DIR,
        Path("/dev/null"),
        _reader_all_managed,
    )
    assert any(p.kind == "hooks_path_bypass" for p in problems)
    bypass = next(p for p in problems if p.kind == "hooks_path_bypass")
    assert "core.hooksPath" in bypass.fix


def test_hookspath_set_to_default_dir_is_ok(vh) -> None:
    """core.hooksPath set to the actual default hooks dir → no problems."""
    problems = vh.check_hooks(
        _DEFAULT_TYPES,
        _HOOKS_DIR,
        _HOOKS_DIR,
        _reader_all_managed,
    )
    assert problems == []


def test_empty_hook_types_handled_sanely(vh) -> None:
    """An empty required-types list yields no problems (nothing to verify)."""
    problems = vh.check_hooks([], _HOOKS_DIR, None, _reader_all_managed)
    assert problems == []


# ---------------------------------------------------------------------------
# Config-parsing wrapper tests — read_required_hook_types(config_path)
# ---------------------------------------------------------------------------


def test_read_required_hook_types_parses_source_of_truth(vh, tmp_path) -> None:
    """`default_install_hook_types` is read from .pre-commit-config.yaml."""
    config = tmp_path / ".pre-commit-config.yaml"
    config.write_text(
        "repos: []\n"
        "default_install_hook_types:\n"
        "  [pre-commit, pre-push, commit-msg, prepare-commit-msg, post-commit]\n",
        encoding="utf-8",
    )
    assert vh.read_required_hook_types(config) == [
        "pre-commit",
        "pre-push",
        "commit-msg",
        "prepare-commit-msg",
        "post-commit",
    ]


def test_read_required_hook_types_missing_key_returns_empty(vh, tmp_path) -> None:
    """A config without the key yields an empty list (handled sanely)."""
    config = tmp_path / ".pre-commit-config.yaml"
    config.write_text("repos: []\n", encoding="utf-8")
    assert vh.read_required_hook_types(config) == []


# ---------------------------------------------------------------------------
# Git-wrapper regression — default hooks dir must be immune to core.hooksPath.
# ---------------------------------------------------------------------------


def test_default_hooks_dir_is_immune_to_hookspath_override(vh, tmp_path) -> None:
    """`git_default_hooks_dir` must resolve to `.git/hooks` even when
    `core.hooksPath` is hijacked — otherwise the bypass guard would compare
    the override against itself and never fire."""
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    default = vh.git_default_hooks_dir(tmp_path)
    assert default == (tmp_path / ".git" / "hooks").resolve()

    subprocess.run(
        ["git", "config", "core.hooksPath", "/dev/null"], cwd=tmp_path, check=True
    )
    # Still the genuine default, NOT the /dev/null override.
    assert vh.git_default_hooks_dir(tmp_path) == default
    # And the config reader reports the override so the guard can compare them.
    assert vh.git_hooks_path_config(tmp_path) == Path("/dev/null").resolve()
