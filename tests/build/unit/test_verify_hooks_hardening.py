"""Hardening (RED) tests for `scripts/validation/verify_hooks.py`.

An nWave adversarial review found `verify-hooks` reports OK in states where
git would NOT actually run the hooks. The existing unit suite
(`test_verify_hooks.py`) injects FAKE `marker_reader` closures into the pure
`check_hooks` core — which is exactly what HID these defects: the fakes never
exercise the real `reader` closure inside `main`, nor the real config-parsing,
nor the real git wrappers.

These tests deliberately drive the REAL path: a real isolated temp git repo
(`tmp_path`), real `.git/hooks/<type>` files with real mode bits, a real
`.pre-commit-config.yaml`, and `main(["--repo-root", ...])` end-to-end. No
fake readers. They pin the CORRECT behaviour; the crafter hardens
`verify_hooks.py` to GREEN.

Test map (RED = expected-fail against current production; PASS = coverage):
  NEW-2  non-executable hook must be flagged             RED
  H1     marker spoofing flagged / genuine accepted      RED (spoof) + PASS (genuine)
  H2     fail-open on missing/empty config               RED
  H3     unparseable yaml -> exit 2 clean                RED
  H5     non-list default_install_hook_types -> exit 2   RED
  H4     git unavailable -> exit 2 clean                 RED
  H6     main() exit codes (0 / 1 / 1)                   PASS
  H7     .resolve() guard (symlink / .. / inverse)       PASS

Conventions follow the neighbouring `test_verify_hooks.py`: importlib loader,
`tests/build/unit/` placement, behavior-first naming.
"""

