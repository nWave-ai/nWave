# ---------------------------------------------------------------------------
# H7 — `.resolve()` guard. core.hooksPath that resolves to the SAME target as
# the default hooks dir (via symlink or `..`) must NOT be flagged as a bypass;
# a genuinely different target MUST be. Removing the production `.resolve()`
# breaks the symlink/`..` cases (raw strings differ).
# ---------------------------------------------------------------------------


def test_hookspath_via_symlink_to_default_not_flagged(vh, tmp_path) -> None:
    """core.hooksPath -> a symlink pointing at `.git/hooks` is authoritative.

    Different path string, same resolved target. EXPECTED-PASS; would FAIL if
    production dropped `.resolve()` (link vs real dir compare unequal).
    """
    _init_repo(tmp_path, types=("pre-commit",))
    _write_hook(tmp_path, "pre-commit", _GENUINE, executable=True)
    real_hooks = tmp_path / ".git" / "hooks"
    link = tmp_path / "hooks-link"
    link.symlink_to(real_hooks, target_is_directory=True)
    subprocess.run(
        ["git", "config", "core.hooksPath", str(link)], cwd=tmp_path, check=True
    )

    rc = _run(vh, tmp_path)

    assert rc == 0  # asserting line — PASS (kills a removed-`.resolve()` mutant)


