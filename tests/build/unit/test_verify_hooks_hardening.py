# A genuine pre-commit hook: the generated-file marker sits as the banner line
# directly under the shebang (line 2), exactly as `pre-commit install` writes
# it, followed by the real hook payload.
_GENUINE = (
    "#!/usr/bin/env bash\n"
    "# File generated by pre-commit: https://pre-commit.com\n"
    "# ID: 138fd403232d2ddd5efb44317e38bf03\n"
    "ARGS=(hook-impl)\n"
    'exec /usr/bin/python3 -mpre_commit hook-impl "${ARGS[@]}"\n'
)

# A FOREIGN script that merely *embeds* the marker string in a buried comment,
# below an attacker payload — NOT a generated banner line. Substring-only
# detection accepts it; a banner/position-aware check must reject it.
_SPOOFED = (
    "#!/usr/bin/env bash\n"
    'echo MALICIOUS >> "$HOME/.pwned"\n'
    "# copied note: File generated by pre-commit (not really, lol)\n"
    "exit 0\n"
)

# A plain foreign/stale script with no marker anywhere.
_FOREIGN = "#!/usr/bin/env bash\necho 'legacy custom hook'\n"


# ---------------------------------------------------------------------------
# Real-repo builders — never touch the real `.git`; everything under tmp_path.
# ---------------------------------------------------------------------------


def _init_repo(root: Path, *, types: tuple[str, ...] = ("pre-commit",)) -> None:
    """Real `git init` + a real `.pre-commit-config.yaml` declaring `types`."""
    subprocess.run(["git", "init", "-q"], cwd=root, check=True)
    type_list = ", ".join(types)
    (root / ".pre-commit-config.yaml").write_text(
        f"repos: []\ndefault_install_hook_types: [{type_list}]\n",
        encoding="utf-8",
    )


def _write_hook(
    root: Path, hook_type: str, content: str, *, executable: bool = True
) -> Path:
    """Write a real hook file into the repo's real `.git/hooks` with mode bits."""
    hooks_dir = root / ".git" / "hooks"
    hooks_dir.mkdir(parents=True, exist_ok=True)
    path = hooks_dir / hook_type
    path.write_text(content, encoding="utf-8")
    path.chmod(0o755 if executable else 0o644)
    return path


def _run(vh, root: Path) -> int:
    """Run the CLI shell end-to-end against a real repo root."""
    return vh.main(["--repo-root", str(root)])


# ---------------------------------------------------------------------------
# NEW-2 — non-executable hook must be FLAGGED (git ignores non-exec hooks).
# Drives the real `reader` closure inside main(): the existing fake-reader
# tests can never see this because they bypass the closure entirely.
# ---------------------------------------------------------------------------


def test_non_executable_hook_is_flagged(vh, tmp_path) -> None:
    """A marker-carrying hook with the exec bit removed must FAIL (git skips it).

    EXPECTED-RED: production's reader closure only checks `is_file()`, so it
    returns the content and reports OK — a false pass.
    """
    _init_repo(tmp_path, types=("pre-commit",))
    _write_hook(tmp_path, "pre-commit", _GENUINE, executable=False)

    rc = _run(vh, tmp_path)

    assert rc == 1  # asserting line — RED (production returns 0)


