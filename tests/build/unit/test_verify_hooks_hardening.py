# H4 — git unavailable (stripped from PATH) must exit 2 cleanly, no traceback.
# A valid config is provided so the exit-2 can only come from git handling,
# not from the earlier missing-config guard.
# ---------------------------------------------------------------------------


def test_git_unavailable_exits_two(vh, tmp_path, monkeypatch) -> None:
    """When `git` cannot be invoked at all, main must exit 2, not crash.

    EXPECTED-RED: `subprocess.run(["git", ...])` raises FileNotFoundError with
    git off PATH; main does not catch it, so the call propagates.
    """
    (tmp_path / ".pre-commit-config.yaml").write_text(
        "repos: []\ndefault_install_hook_types: [pre-commit]\n", encoding="utf-8"
    )
    empty_bin = tmp_path / "empty-bin"
    empty_bin.mkdir()
    # No `git` resolvable on PATH -> the git subprocess raises FileNotFoundError.
    monkeypatch.setenv("PATH", str(empty_bin))

    rc = _run(vh, tmp_path)

    assert rc == 2  # asserting line — RED (production raises FileNotFoundError)


